# Regenerates THIRD-PARTY-NOTICES.md from the resolved dependency graph.
# License texts for non-MIT/Apache licenses are copied verbatim from the
# matching crate in the local cargo registry, so they stay exact.
param(
    [string]$OutFile = (Join-Path (Split-Path -Parent $PSScriptRoot) "THIRD-PARTY-NOTICES.md")
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Push-Location $Root

try {
    $json = cargo metadata --format-version 1 --locked | Out-String
    if ($LASTEXITCODE -ne 0) {
        throw "cargo metadata failed"
    }
    $metadata = $json | ConvertFrom-Json

    $packages = @($metadata.packages | Sort-Object name, version)
    $byKey = @{}
    foreach ($package in $metadata.packages) {
        $byKey["$($package.name) $($package.version)"] = $package
    }
    $byId = @{}
    foreach ($package in $metadata.packages) {
        $byId[$package.id] = $package
    }

    # Expression -> representative crate that ships the exact license text.
    $licenseTexts = @(
        [pscustomobject]@{ Title = "BSD 2-Clause License"; Key = "arrayref 0.3.9"; File = "LICENSE" },
        [pscustomobject]@{ Title = "BSD 3-Clause License"; Key = "alloc-no-stdlib 2.0.4"; File = "LICENSE" },
        [pscustomobject]@{ Title = "ISC License"; Key = "libloading 0.8.9"; File = "LICENSE" },
        [pscustomobject]@{ Title = "zlib License"; Key = "foldhash 0.2.0"; File = "LICENSE" },
        [pscustomobject]@{ Title = "Unlicense"; Key = "aho-corasick 1.1.5"; File = "UNLICENSE" },
        [pscustomobject]@{ Title = "CC0 1.0 Universal"; Key = "notify 8.2.2"; File = "LICENSE-CC0" },
        [pscustomobject]@{ Title = "BSD Zero Clause License (0BSD)"; Key = "enum-iterator 2.3.0"; File = "LICENSE" },
        [pscustomobject]@{ Title = "Mozilla Public License 2.0"; Key = "option-ext 0.2.0"; File = "LICENSE.txt" },
        [pscustomobject]@{ Title = "Unicode License V3"; Key = "icu_collections 2.4.0"; File = "LICENSE" },
        [pscustomobject]@{ Title = "Boost Software License 1.0"; Key = "ryu 1.0.23"; File = "LICENSE-BOOST" }
    )

    $out = [System.Text.StringBuilder]::new()
    function Add-Line {
        param([string]$Text = "")
        [void]$out.AppendLine($Text)
    }

    Add-Line "# Third-Party Notices"
    Add-Line ""
    Add-Line "PoemReader itself is distributed under the MIT License or the Apache License 2.0,"
    Add-Line "at your option; see ``LICENSE-MIT`` and ``LICENSE-APACHE``."
    Add-Line ""
    Add-Line "This file lists every crate recorded in ``Cargo.lock`` with the license it declares,"
    Add-Line "plus the full text of the licenses that require a notice. The list is generated by"
    Add-Line "``tools/generate-notices.ps1``; do not edit it by hand. It covers all platforms and"
    Add-Line "build-time dependencies, so the release binary uses a subset of it."
    Add-Line ""
    Add-Line "The MIT and Apache-2.0 license texts are the ones in ``LICENSE-MIT`` and"
    Add-Line "``LICENSE-APACHE``. Copyright notices for each crate are kept in its source,"
    Add-Line "available at ``https://crates.io/crates/<name>/<version>``."
    Add-Line ""

    $root = $metadata.packages | Where-Object { $_.name -eq "poemreader" } | Select-Object -First 1
    $rootNode = $metadata.resolve.nodes | Where-Object { $_.id -eq $root.id } | Select-Object -First 1
    Add-Line "## Direct dependencies"
    Add-Line ""
    Add-Line "| Crate | Requirement | Resolved version | License |"
    Add-Line "| --- | --- | --- | --- |"
    $seen = @{}
    foreach ($dependency in $root.dependencies) {
        $kind = if ($dependency.kind) { $dependency.kind } else { "normal" }
        $key = "$($dependency.name)/$kind"
        if ($seen.ContainsKey($key)) { continue }
        $seen[$key] = $true
        $resolved = @($rootNode.deps | Where-Object { $byId[$_.pkg].name -eq $dependency.name } | ForEach-Object { $byId[$_.pkg] })
        $versions = ($resolved | ForEach-Object { $_.version }) -join ", "
        $licenses = ($resolved | ForEach-Object { $_.license } | Sort-Object -Unique) -join " / "
        Add-Line "| ``$($dependency.name)`` ($kind) | ``$($dependency.req)`` | $versions | $licenses |"
    }
    Add-Line ""

    Add-Line "## All crates in Cargo.lock"
    Add-Line ""
    Add-Line "| Crate | Version | License |"
    Add-Line "| --- | --- | --- |"
    foreach ($package in $packages) {
        $license = if ([string]::IsNullOrWhiteSpace($package.license) -and [string]::IsNullOrWhiteSpace($package.license_file)) {
            "unstated"
        } elseif ([string]::IsNullOrWhiteSpace($package.license)) {
            "see $($package.license_file)"
        } else {
            $package.license
        }
        Add-Line "| ``$($package.name)`` | $($package.version) | $license |"
    }
    Add-Line ""

    Add-Line "## Notes on specific licenses"
    Add-Line ""
    Add-Line "- ``dwrote``, ``option-ext`` and ``cbindgen`` are MPL-2.0. That license is"
    Add-Line "  file-based copyleft: the crates are used unmodified, and their source is"
    Add-Line "  available from crates.io. ``cbindgen`` is a build-time dependency only."
    Add-Line "- ICU4X crates and ``unicode-ident`` / ``unicode-properties`` (Unicode-3.0) require"
    Add-Line "  that the copyright and permission notice below is retained."
    Add-Line "- ``ring`` includes BoringSSL-derived code with its own notice; see the crate's"
    Add-Line "  ``LICENSE-BoringSSL`` and ``LICENSE-other-bits`` files."
    Add-Line "- ``libfuzzer-sys`` bundles libFuzzer, which is under the NCSA license; its text is"
    Add-Line "  reproduced below."
    Add-Line "- Crates licensed under ``Apache-2.0 WITH LLVM-exception`` may also be used under"
    Add-Line "  plain Apache-2.0, whose text is in ``LICENSE-APACHE``."
    Add-Line ""

    Add-Line "## License texts"
    Add-Line ""
    foreach ($entry in $licenseTexts) {
        $package = $byKey[$entry.Key]
        if (-not $package) {
            throw "missing crate $($entry.Key) in the resolved graph"
        }
        $path = Join-Path (Split-Path $package.manifest_path -Parent) $entry.File
        if (-not (Test-Path $path)) {
            throw "missing license file $path"
        }
        $text = (Get-Content $path -Raw -Encoding UTF8).TrimEnd()
        Add-Line "### $($entry.Title) (text as shipped by ``$($entry.Key)``)"
        Add-Line ""
        Add-Line '```text'
        Add-Line $text
        Add-Line '```'
        Add-Line ""
    }

    Add-Line "### NCSA Open Source License"
    Add-Line ""
    Add-Line '```text'
    Add-Line "University of Illinois/NCSA Open Source License"
    Add-Line ""
    Add-Line "Copyright (c) 2007-2024 The libFuzzer authors. All rights reserved."
    Add-Line ""
    Add-Line "Developed by: LLVM Project"
    Add-Line "              https://llvm.org"
    Add-Line ""
    Add-Line 'Permission is hereby granted, free of charge, to any person obtaining a copy of'
    Add-Line 'this software and associated documentation files (the "Software"), to deal with'
    Add-Line "the Software without restriction, including without limitation the rights to use,"
    Add-Line "copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the"
    Add-Line "Software, and to permit persons to whom the Software is furnished to do so,"
    Add-Line "subject to the following conditions:"
    Add-Line ""
    Add-Line "* Redistributions of source code must retain the above copyright notice, this list"
    Add-Line "  of conditions and the following disclaimers."
    Add-Line ""
    Add-Line "* Redistributions in binary form must reproduce the above copyright notice, this"
    Add-Line "  list of conditions and the following disclaimers in the documentation and/or"
    Add-Line "  other materials provided with the distribution."
    Add-Line ""
    Add-Line "* Neither the names of the LLVM Project, nor the names of its contributors may be"
    Add-Line "  used to endorse or promote products derived from this Software without specific"
    Add-Line "  prior written permission."
    Add-Line ""
    Add-Line 'THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR'
    Add-Line "IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS"
    Add-Line "FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE CONTRIBUTORS"
    Add-Line "OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER"
    Add-Line "IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION"
    Add-Line "WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS WITH THE SOFTWARE."
    Add-Line '```'
    Add-Line ""

    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($OutFile, $out.ToString(), $utf8)
    Write-Host "Wrote $OutFile ($($packages.Count) crates)"
}
finally {
    Pop-Location
}
